import { chromium } from '@playwright/test';
const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page = await browser.newPage({viewport:{width:1080,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('file:///Users/desenyon/Developer/synthesis/docs/design/native-review-preview.html');
const frame=page.frameLocator('iframe');
await frame.locator('#syntehsis-native').waitFor();
await page.waitForTimeout(1000);
await page.screenshot({path:'docs/design/native-review-desktop.png',fullPage:true});
await frame.getByRole('button',{name:'Connections',exact:true}).click();
await frame.locator('#sn-graph').getByRole('button',{name:'Mira Vale Character'}).click();
if(await frame.locator('#sn-title').textContent()!=='Mira Vale')throw new Error('Graph navigation failed');
await frame.getByRole('button',{name:'Review 1',exact:true}).click();
await frame.getByRole('button',{name:'Preview approval',exact:true}).click();
await frame.getByRole('button',{name:'Finish approval preview',exact:true}).click();
await frame.locator('#sn-review-feedback').filter({hasText:'Approval preview complete'}).waitFor();
